
import numpy as np
import torch
from torch.utils.data import DataLoader, random_split
from functools import partial

from src.datasets import Datasets
from evaluate_refine import carica_stage1, collate_fn, calcola_mre_sdr, NOMI

# ── Parameters (tunable) ─────────────────────────────────────────────

# Stage-1 MRE above this threshold -> landmark is routed to Stage 2
STAGE2_THRESHOLD_MM = 1.5

# Loss weight: below this threshold weight=1.0 (no boost); above it,
# weight grows linearly with the error up to a maximum
PESO_BASELINE_MM = 1.0
PESO_SLOPE       = 1.0     # +1.0 weight per mm of error above baseline
PESO_MAX         = 4.0

# Sigma of the Gaussian heatmap: same logic, in pixels (256px heatmap)
SIGMA_BASE_PX      = 4.0   # must match CONFIG["sigma"] in train_heatmap.py
SIGMA_BASELINE_MM  = 1.0
SIGMA_SLOPE        = 0.8
SIGMA_MAX_PX       = 7.0

CONFIG = {
    "aariz_path":         "data/Aariz",
    "isbi_path":          "data/Cepha400",
    "num_landmarks":      26,
    "batch_size":         2,
    "val_split":          0.2,
    "img_size":           512,
    "heatmap_size":       256,
    "stage1_path":        "modello_heatmap.pth",
    "hrnet_channels":     [192, 384, 768, 1536],
    "usa_tta":            False,   # no TTA: we want the "raw" Stage 1 error
    "larghezza_orig_px":  2400,
    "sdr_thresholds_mm":  [2.0, 2.5, 3.0, 4.0],
}


def clamp(v, lo, hi):
    """Clamp value v to the closed interval [lo, hi], 
    returning v unchanged if it already falls within the range or 
    the nearest bound (lo or hi) otherwise."""
    return max(lo, min(hi, v))


def genera_statistiche(mre_lm):
    """Takes a list of per-landmark MRE values in mm 
    (None for landmarks with no valid samples) and derives, 
    for each landmark with a valid MRE, whether it should be 
    routed to Stage 2 (when its MRE exceeds STAGE2_THRESHOLD_MM), 
    a loss weight growing linearly with the error above 
    PESO_BASELINE_MM and capped at PESO_MAX, and a heatmap sigma in 
    pixels growing linearly with the error above SIGMA_BASELINE_MM 
    and capped at SIGMA_MAX_PX, returning the resulting refine_mask set, 
    pesi dict and sigma dict."""
    refine_mask, pesi, sigma = set(), {}, {}
    for i, mre in enumerate(mre_lm):
        if mre is None:
            continue
        if mre > STAGE2_THRESHOLD_MM:
            refine_mask.add(i)
        if mre > PESO_BASELINE_MM:
            pesi[i] = round(clamp(1.0 + PESO_SLOPE * (mre - PESO_BASELINE_MM), 1.0, PESO_MAX), 2)
        if mre > SIGMA_BASELINE_MM:
            sigma[i] = round(clamp(SIGMA_BASE_PX + SIGMA_SLOPE * (mre - SIGMA_BASELINE_MM), SIGMA_BASE_PX, SIGMA_MAX_PX), 2)
    return refine_mask, pesi, sigma


def scrivi_modulo(path, mre_lm, refine_mask, pesi, sigma):
    """Writes the per-landmark MRE values, the Stage 2 refinement mask, the loss weights and the heatmap sigmas out to a standalone Python module at the given path, which other scripts such as heatmap_utils.py and model_refine.py can later import as REFINE_LANDMARK_MASK, PESI_LANDMARK and SIGMA_PER_LANDMARK, together with a header docstring documenting the MRE values that were used to compute the thresholds."""
    nomi = NOMI if len(NOMI) == len(mre_lm) else [str(i) for i in range(len(mre_lm))]
    with open(path, "w") as f:
        f.write('"""\nAuto-generated by analyze_landmark_difficulty.py — do NOT edit by hand.\n')
        f.write("Re-run the script after every Stage 1 retraining to regenerate.\n\n")
        f.write("Stage-1 MRE (mm, no TTA, no Stage 2) on the validation set used to compute the thresholds:\n")
        for i, mre in enumerate(mre_lm):
            nome = nomi[i] if i < len(nomi) else str(i)
            val = f"{mre:.2f}mm" if mre is not None else "n/a"
            f.write(f"  {i:2d} {nome:6s} {val}\n")
        f.write(f"\nStage 2 threshold: MRE > {STAGE2_THRESHOLD_MM}mm | "
                f"weight/sigma baseline: {PESO_BASELINE_MM}mm / {SIGMA_BASELINE_MM}mm\n\"\"\"\n\n")
 
        f.write("REFINE_LANDMARK_MASK = {\n")
        for i in sorted(refine_mask):
            nome = nomi[i] if i < len(nomi) else str(i)
            f.write(f"    {i},  # {nome} (MRE={mre_lm[i]:.2f}mm)\n")
        f.write("}\n\n")
 
        f.write("PESI_LANDMARK = {\n")
        for i, p in sorted(pesi.items()):
            nome = nomi[i] if i < len(nomi) else str(i)
            f.write(f"    {i}: {p},  # {nome} (MRE={mre_lm[i]:.2f}mm)\n")
        f.write("}\n\n")
 
        f.write("SIGMA_PER_LANDMARK = {\n")
        for i, s in sorted(sigma.items()):
            nome = nomi[i] if i < len(nomi) else str(i)
            f.write(f"    {i}: {s},  # {nome} (MRE={mre_lm[i]:.2f}mm)\n")
        f.write("}\n")
    print(f"Wrote {path}")


def genera_landmark_stats(stage1_path=None, aariz_path=None, isbi_path=None,
                           device=None, output_path="src/landmark_stats.py"):
    """Reusable entry point that loads the Stage 1 model, evaluates it on the validation set to obtain the per-landmark MRE, derives the refinement mask, loss weights and heatmap sigmas from it, and writes them to output_path, accepting optional overrides for the Stage 1 checkpoint path, the Aariz and ISBI dataset paths and the torch device, and returning the same mre_lm, refine_mask, pesi and sigma values that were written to disk so that it can be called standalone or automatically at the end of train_heatmap.py."""
    config = dict(CONFIG)
    if stage1_path: config["stage1_path"] = stage1_path
    if aariz_path:  config["aariz_path"]  = aariz_path
    if isbi_path:   config["isbi_path"]   = isbi_path
 
    device = device or torch.device("cuda" if torch.cuda.is_available() else "cpu")
    stage1 = carica_stage1(config, device)
 
    dataset = Datasets(aariz_path=config["aariz_path"], isbi_path=config["isbi_path"])
    n_val = int(len(dataset) * config["val_split"])
    _, val_ds = random_split(dataset, [len(dataset) - n_val, n_val],
                              generator=torch.Generator().manual_seed(42))
    val_loader = DataLoader(val_ds, batch_size=config["batch_size"], shuffle=False,
                             num_workers=0, collate_fn=partial(collate_fn, img_size=config["img_size"]))
 
    print("Evaluating Stage 1 (no TTA, no Stage 2) on the validation set...")
    _, mre_lm, _, _ = calcola_mre_sdr(stage1, None, val_loader, device, config)
 
    refine_mask, pesi, sigma = genera_statistiche(mre_lm)
    scrivi_modulo(output_path, mre_lm, refine_mask, pesi, sigma)
    print(f"Landmarks routed to Stage 2 ({len(refine_mask)}/{config['num_landmarks']}): {sorted(refine_mask)}")
    return mre_lm, refine_mask, pesi, sigma


def main():
    """Entry point used when the script is run standalone, running the full statistics generation pipeline with the default configuration and printing a short completion message."""
    print(f"Device: {torch.device('cuda' if torch.cuda.is_available() else 'cpu')}")
    genera_landmark_stats()
    print("Re-run train_heatmap.py / train_refine.py as usual: "
          "they will now read src/landmark_stats.py instead of the hardcoded dictionaries.")
 
 
if __name__ == "__main__":
    main()